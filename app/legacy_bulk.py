"""Fast transactional Weinstein legacy import into MKD.

Uses PostgreSQL COPY into a temporary staging table, then set-based validation
and insertion. No connection to Weinstein, no invented MIC or PIT timestamps.
Dry-run is the default. Requires schema 0004.
"""
import argparse
import csv
import json
from pathlib import Path

from sqlalchemy import text
from app.db import engine

EXPECTED = ("symbol","name","currency","day","open","high","low","close","volume")

def migrate(path: Path, *, apply=False):
    with path.open(newline="", encoding="utf-8") as f:
        header = tuple(next(csv.reader(f)))
    if header != EXPECTED:
        raise ValueError(f"CSV columns must be {EXPECTED}, got {header}")
    with engine.connect() as connection:
        transaction = connection.begin()
        try:
            connection.execute(text("""CREATE TEMP TABLE mkd_legacy_stage (
                symbol text NOT NULL, name text NOT NULL, currency text NOT NULL,
                day date NOT NULL, open numeric NOT NULL, high numeric NOT NULL,
                low numeric NOT NULL, close numeric NOT NULL, volume bigint NOT NULL
            ) ON COMMIT DROP"""))
            # COPY streams the CSV in bounded chunks, avoiding Python row objects.
            raw = connection.connection.driver_connection
            with raw.cursor() as cursor:
                with cursor.copy("COPY mkd_legacy_stage FROM STDIN WITH (FORMAT CSV, HEADER TRUE)") as copy:
                    with path.open("rb") as source:
                        while chunk := source.read(1024 * 1024):
                            copy.write(chunk)
            count = connection.execute(text("SELECT count(*) FROM mkd_legacy_stage")).scalar_one()
            distinct_count = connection.execute(text(
                "SELECT count(*) FROM (SELECT DISTINCT symbol, day FROM mkd_legacy_stage) x")).scalar_one()
            if count != distinct_count:
                raise ValueError("duplicate symbol/day in source")
            invalid = connection.execute(text("""SELECT count(*) FROM mkd_legacy_stage
                WHERE symbol = '' OR name = '' OR length(symbol) > 80
                OR length(name) > 250 OR length(currency) <> 3
                OR open < 0 OR low < 0 OR high < greatest(open,close,low)
                OR low > least(open,close) OR volume < 0
                OR open > 9999999999999999 OR high > 9999999999999999
                OR low > 9999999999999999 OR close > 9999999999999999
            """)).scalar_one()
            if invalid:
                raise ValueError(f"invalid source rows: {invalid}")
            metadata_conflicts = connection.execute(text("""SELECT count(*) FROM (
                SELECT symbol FROM mkd_legacy_stage
                GROUP BY symbol HAVING count(DISTINCT (name,currency)) > 1
            ) x""")).scalar_one()
            if metadata_conflicts:
                raise ValueError(f"inconsistent source metadata: {metadata_conflicts}")
            mapping_conflicts = connection.execute(text("""SELECT count(*) FROM (
                SELECT DISTINCT s.symbol, s.name, s.currency FROM mkd_legacy_stage s
            ) s JOIN legacy_symbol_map m ON m.symbol=s.symbol
            WHERE m.name <> s.name OR m.currency <> s.currency""")).scalar_one()
            if mapping_conflicts:
                raise ValueError(f"existing identity conflicts: {mapping_conflicts}")
            price_conflicts = connection.execute(text("""SELECT count(*) FROM mkd_legacy_stage s
                JOIN legacy_symbol_map m ON m.symbol=s.symbol
                JOIN eod_bars b ON b.instrument_id=m.instrument_id
                  AND b.session_date=s.day AND b.provider='yahoo'
                WHERE b.currency <> s.currency OR b.open <> s.open
                   OR b.high <> s.high OR b.low <> s.low
                   OR b.close <> s.close OR b.volume <> s.volume
                   OR b.quality_status <> 'legacy_unverified'
            """)).scalar_one()
            if price_conflicts:
                raise ValueError(f"conflicting existing bars: {price_conflicts}")
            symbols = connection.execute(text("SELECT count(DISTINCT symbol) FROM mkd_legacy_stage")).scalar_one()
            existing = connection.execute(text("""SELECT count(*) FROM mkd_legacy_stage s
                JOIN legacy_symbol_map m ON m.symbol=s.symbol
                JOIN eod_bars b ON b.instrument_id=m.instrument_id
                  AND b.session_date=s.day AND b.provider='yahoo'
            """)).scalar_one()
            report = {"source_bars":count,"symbols":symbols,"existing_bars":existing,
                      "new_bars":count-existing,"invalid_rows":invalid,
                      "identity_conflicts":mapping_conflicts,"bar_conflicts":price_conflicts}
            if apply:
                # UUIDs generated by PostgreSQL's built-in md5 expression without extensions.
                connection.execute(text("""CREATE TEMP TABLE mkd_new_symbols ON COMMIT DROP AS
                    SELECT DISTINCT s.symbol, s.name, s.currency,
                      (substr(md5('mkd-legacy-yahoo:' || s.symbol),1,8) || '-' ||
                       substr(md5('mkd-legacy-yahoo:' || s.symbol),9,4) || '-' ||
                       substr(md5('mkd-legacy-yahoo:' || s.symbol),13,4) || '-' ||
                       substr(md5('mkd-legacy-yahoo:' || s.symbol),17,4) || '-' ||
                       substr(md5('mkd-legacy-yahoo:' || s.symbol),21,12))::uuid AS instrument_id
                    FROM mkd_legacy_stage s
                    WHERE NOT EXISTS (SELECT 1 FROM legacy_symbol_map m WHERE m.symbol=s.symbol)
                """))
                connection.execute(text("""INSERT INTO instruments(id,name,asset_type,status)
                    SELECT instrument_id,name,
                      CASE WHEN symbol IN ('SPY','EXSA.DE') THEN 'etf' ELSE 'stock' END,
                      'active' FROM mkd_new_symbols"""))
                connection.execute(text("""INSERT INTO legacy_symbol_map(symbol,currency,name,instrument_id)
                    SELECT symbol,currency,name,instrument_id FROM mkd_new_symbols"""))
                connection.execute(text("""INSERT INTO eod_bars(
                    instrument_id,session_date,provider,revision,currency,
                    open,high,low,close,volume,published_at,first_available_at,
                    ingested_at,quality_status)
                    SELECT m.instrument_id,s.day,'yahoo',1,s.currency,
                      s.open,s.high,s.low,s.close,s.volume,NULL,NULL,
                      now(),'legacy_unverified'
                    FROM mkd_legacy_stage s
                    JOIN legacy_symbol_map m ON m.symbol=s.symbol
                    WHERE NOT EXISTS (
                      SELECT 1 FROM eod_bars b
                      WHERE b.instrument_id=m.instrument_id
                        AND b.session_date=s.day AND b.provider='yahoo')
                """))
                transaction.commit()
                report["status"]="applied"
            else:
                transaction.rollback()
                report["status"]="dry_run"
            return report
        except BaseException:
            if transaction.is_active:
                transaction.rollback()
            raise

def main():
    p=argparse.ArgumentParser()
    p.add_argument("csv",type=Path)
    p.add_argument("--apply",action="store_true")
    p.add_argument("--report",type=Path)
    args=p.parse_args()
    report=migrate(args.csv,apply=args.apply)
    payload=json.dumps(report,indent=2)
    if args.report:
        args.report.write_text(payload+"\n",encoding="utf-8")
    print(payload)

if __name__=="__main__":
    main()
